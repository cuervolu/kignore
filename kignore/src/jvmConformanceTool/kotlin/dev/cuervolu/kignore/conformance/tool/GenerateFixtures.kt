package dev.cuervolu.kignore.conformance.tool

import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.exists
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.name
import kotlin.io.path.readText
import kotlin.io.path.writeText
import kotlin.system.exitProcess

/*
 * Development tool that asks Git for the expected result of every path in conformance/scenarios and
 * writes the answers to conformance/fixtures and to the embedded copy used by the commonTest sources.
 *
 * Run from the repository root through Gradle:
 *
 *   ./gradlew generateConformanceFixtures
 *   ./gradlew checkConformanceFixtures
 *
 * The format is described in conformance/README.md. The Kotlin tests never run this code.
 */

private const val COMMAND = "git check-ignore --no-index -v -n -z --stdin"
private val KINDS = setOf("normative", "git-quirk", "platform")
private val RESULT_RULE_SEPARATOR = " # "

private val DEFAULT_CONFIG =
    linkedMapOf(
        "core.ignorecase" to "false",
        "core.precomposeunicode" to "false",
        "core.quotepath" to "false",
        "core.autocrlf" to "false",
        "core.symlinks" to "false",
    )

private val ROOT: Path = Path.of("conformance")
private val SCENARIOS: Path = ROOT.resolve("scenarios")
private val FIXTURES: Path = ROOT.resolve("fixtures")
private val EMBEDDED: Path =
    Path.of("kignore/src/commonTest/kotlin/dev/cuervolu/kignore/conformance/ConformanceData.kt")

private data class FileSpec(
    val path: String,
    val content: String,
    val noEol: Boolean,
)

private data class CheckSpec(
    val path: String,
    val result: String?,
    val rule: String?,
)

private data class Scenario(
    val id: String,
    val kind: String,
    val spec: String,
    val note: String?,
    val config: Map<String, String>,
    val files: List<FileSpec>,
    val checks: List<CheckSpec>,
)

fun main(args: Array<String>) {
    val check = args.firstOrNull() == "--check"
    check(Files.isDirectory(SCENARIOS)) { "Run from the repository root, missing $SCENARIOS" }
    val gitVersion = runGit(listOf("git", "--version"), null, emptyMap(), null).trim()
    val sources = SCENARIOS.listDirectoryEntries("*.txt").sorted()

    val generated = linkedMapOf<String, String>()
    val ids = HashSet<String>()
    var scenarioCount = 0
    var checkCount = 0
    for (source in sources) {
        val scenarios = parse(source.readText(), source.toString())
        val out = StringBuilder()
        out.append("# Generated by GenerateFixtures. Do not edit.\n")
        out.append("# git: ").append(gitVersion).append('\n')
        out.append("# command: ").append(COMMAND).append('\n')
        out.append("# defaults:")
        DEFAULT_CONFIG.forEach { (k, v) ->
            out
                .append(' ')
                .append(k)
                .append('=')
                .append(v)
        }
        out.append('\n')
        out.append("# source: conformance/scenarios/").append(source.name).append('\n')
        for (scenario in scenarios) {
            check(ids.add(scenario.id)) { "Duplicate scenario id ${scenario.id}" }
            val resolved = OracleRun.resolve(scenario)
            scenarioCount++
            checkCount += resolved.checks.size
            out.append('\n')
            write(out, resolved)
        }
        generated[source.name.removeSuffix(".txt")] = out.toString()
    }

    if (check) {
        checkAgainstDisk(generated)
    } else {
        FIXTURES.createDirectories()
        for ((name, text) in generated) FIXTURES.resolve("$name.txt").writeText(text)
        EMBEDDED.parent.createDirectories()
        EMBEDDED.writeText(embedded(generated))
    }
    println("${if (check) "Checked" else "Generated"} $scenarioCount scenarios, $checkCount cases with $gitVersion")
}

// Parsing

private fun parse(
    text: String,
    origin: String,
): List<Scenario> {
    val result = ArrayList<Scenario>()
    var id: String? = null
    var kind: String? = null
    var spec: String? = null
    var note: String? = null
    var config = linkedMapOf<String, String>()
    var files = ArrayList<FileSpec>()
    var checks = ArrayList<CheckSpec>()
    var filePath = ""
    var noEol = false
    var fileLines: ArrayList<String>? = null

    fun flushFile() {
        fileLines?.let { files.add(fileSpec(filePath, noEol, it)) }
        fileLines = null
    }

    fun flushScenario(where: String) {
        val current = id ?: return
        result.add(finish(current, kind, spec, note, config, files, checks, where))
    }

    text.split("\n").forEachIndexed { n, line ->
        val where = "$origin:${n + 1}"
        check(!line.endsWith("\r")) { "$where: CR in fixture source, use `r" }
        if (line.startsWith("|")) {
            val lines = checkNotNull(fileLines) { "$where: content line outside a file" }
            check(line.length == 1 || line[1] == ' ') { "$where: expected '| '" }
            lines.add(if (line.length > 2) line.substring(2) else "")
            return@forEachIndexed
        }
        flushFile()
        if (line.isEmpty() || line.startsWith("#")) return@forEachIndexed
        val space = line.indexOf(' ')
        val key = if (space < 0) line else line.substring(0, space)
        val rest = if (space < 0) "" else line.substring(space + 1)
        when (key) {
            "scenario" -> {
                flushScenario(where)
                id = rest
                kind = null
                spec = null
                note = null
                config = linkedMapOf()
                files = ArrayList()
                checks = ArrayList()
            }

            "kind" -> {
                kind = rest
            }

            "spec" -> {
                spec = rest
            }

            "note" -> {
                note = rest
            }

            "config" -> {
                val eq = rest.indexOf('=')
                config[rest.substring(0, eq)] = rest.substring(eq + 1)
            }

            "file" -> {
                val parts = rest.split(" ")
                filePath = unescape(parts[0])
                noEol = parts.getOrNull(1) == "noeol"
                fileLines = ArrayList()
            }

            "path" -> {
                val token = rest.substringBefore(" => ")
                checks.add(CheckSpec(unescape(token), null, null))
            }

            else -> {
                error("$where: unknown directive '$key'")
            }
        }
    }
    flushFile()
    flushScenario(origin)
    return result
}

private fun fileSpec(
    path: String,
    noEol: Boolean,
    raw: List<String>,
): FileSpec {
    val content = StringBuilder()
    raw.forEachIndexed { i, line ->
        content.append(unescape(line))
        if (i < raw.size - 1 || !noEol) content.append('\n')
    }
    return FileSpec(path, content.toString(), noEol)
}

private fun finish(
    id: String,
    kind: String?,
    spec: String?,
    note: String?,
    config: Map<String, String>,
    files: List<FileSpec>,
    checks: List<CheckSpec>,
    where: String,
): Scenario {
    check(kind != null && kind in KINDS) { "$where: bad kind in $id" }
    check(!spec.isNullOrBlank()) { "$where: missing spec in $id" }
    check(checks.isNotEmpty()) { "$where: no paths in $id" }
    check(checks.map { it.path }.toSet().size == checks.size) { "$where: duplicate path in $id" }
    return Scenario(id, kind, spec, note, config, files, checks)
}

// Escapes shared with the Kotlin fixture parser, introduced by a backtick: `` `n `r `t `s `uXXXX `u{X...}
// The backtick is used instead of the backslash so gitignore escapes can be written as they are.

private fun unescape(s: String): String {
    val b = StringBuilder()
    var i = 0
    while (i < s.length) {
        val c = s[i]
        if (c != '`') {
            b.append(c)
            i++
            continue
        }
        when (val e = s[++i]) {
            '`' -> {
                b.append('`')
            }

            'n' -> {
                b.append('\n')
            }

            'r' -> {
                b.append('\r')
            }

            't' -> {
                b.append('\t')
            }

            's' -> {
                b.append(' ')
            }

            'u' -> {
                if (s[i + 1] == '{') {
                    val end = s.indexOf('}', i)
                    b.appendCodePoint(s.substring(i + 2, end).toInt(16))
                    i = end
                } else {
                    b.append(s.substring(i + 1, i + 5).toInt(16).toChar())
                    i += 4
                }
            }

            else -> {
                error("Unknown escape `$e in $s")
            }
        }
        i++
    }
    return b.toString()
}

/** Escapes what is invisible or ambiguous so the text files stay readable and stable under editors. */
private fun escape(
    s: String,
    escapeSpaces: Boolean,
    escapeTrailingSpace: Boolean,
): String {
    val b = StringBuilder()
    var trailingStart = s.length
    while (trailingStart > 0 && (s[trailingStart - 1] == ' ' || s[trailingStart - 1] == '\t')) trailingStart--
    var i = 0
    while (i < s.length) {
        val cp = s.codePointAt(i)
        when {
            cp == '`'.code -> {
                b.append("``")
            }

            cp == '\n'.code -> {
                b.append("`n")
            }

            cp == '\r'.code -> {
                b.append("`r")
            }

            cp == '\t'.code -> {
                b.append("`t")
            }

            cp == ' '.code && (escapeSpaces || (escapeTrailingSpace && i >= trailingStart)) -> {
                b.append("`s")
            }

            cp == ' '.code -> {
                b.append(' ')
            }

            isInvisible(cp) -> {
                if (cp <= 0xFFFF) b.append("`u%04X".format(cp)) else b.append("`u{%X}".format(cp))
            }

            else -> {
                b.appendCodePoint(cp)
            }
        }
        i += Character.charCount(cp)
    }
    return b.toString()
}

private val INVISIBLE_TYPES =
    setOf(
        Character.CONTROL,
        Character.FORMAT,
        Character.NON_SPACING_MARK,
        Character.ENCLOSING_MARK,
        Character.COMBINING_SPACING_MARK,
        Character.SPACE_SEPARATOR,
        Character.LINE_SEPARATOR,
        Character.PARAGRAPH_SEPARATOR,
        Character.UNASSIGNED,
        Character.PRIVATE_USE,
        Character.SURROGATE,
    ).map { it.toInt() }.toSet()

private fun isInvisible(cp: Int): Boolean = cp < 0x20 || cp == 0x7F || Character.getType(cp) in INVISIBLE_TYPES

// Writing

private fun write(
    out: StringBuilder,
    sc: Scenario,
) {
    out.append("scenario ").append(sc.id).append('\n')
    out.append("kind ").append(sc.kind).append('\n')
    out.append("spec ").append(sc.spec).append('\n')
    sc.note?.let { out.append("note ").append(it).append('\n') }
    sc.config.forEach { (k, v) ->
        out
            .append("config ")
            .append(k)
            .append('=')
            .append(v)
            .append('\n')
    }
    for (f in sc.files) {
        out
            .append("file ")
            .append(escape(f.path, true, false))
            .append(if (f.noEol) " noeol" else "")
            .append('\n')
        val body = if (f.noEol) f.content else f.content.removeSuffix("\n")
        if (f.noEol || f.content.isNotEmpty()) appendContent(out, body.split("\n"))
    }
    for (c in sc.checks) {
        out
            .append("path ")
            .append(escape(c.path, true, false))
            .append(" => ")
            .append(c.result)
        c.rule?.let { out.append(RESULT_RULE_SEPARATOR).append(escape(it, false, false)) }
        out.append('\n')
    }
}

private fun appendContent(
    out: StringBuilder,
    lines: List<String>,
) {
    for (line in lines) {
        val escaped = escape(line, false, true)
        out.append(if (escaped.isEmpty()) "|" else "| $escaped").append('\n')
    }
}

// Oracle

private object OracleRun {
    fun resolve(sc: Scenario): Scenario {
        val tmp = Files.createTempDirectory("kignore-oracle")
        try {
            val emptyConfig = tmp.resolve("empty.gitconfig").also { it.writeText("") }
            val emptyExcludes = tmp.resolve("empty.excludes").also { it.writeText("") }
            val emptyTemplate = Files.createDirectory(tmp.resolve("template"))
            val home = Files.createDirectory(tmp.resolve("home"))
            val repo = Files.createDirectory(tmp.resolve("repo"))
            val env =
                linkedMapOf(
                    "GIT_CONFIG_GLOBAL" to emptyConfig.toString(),
                    "GIT_CONFIG_SYSTEM" to emptyConfig.toString(),
                    "GIT_CONFIG_NOSYSTEM" to "1",
                    "HOME" to home.toString(),
                    "USERPROFILE" to home.toString(),
                    "XDG_CONFIG_HOME" to home.toString(),
                )

            runGit(listOf("git", "init", "-q", "--template=$emptyTemplate"), repo, env, null)
            val config = LinkedHashMap(DEFAULT_CONFIG)
            config["core.excludesFile"] = emptyExcludes.toString()
            config.putAll(sc.config)
            for ((k, v) in config) runGit(listOf("git", "config", "--local", k, v), repo, env, null)

            for (f in sc.files) {
                val target = repo.resolve(f.path)
                check(!target.exists()) { "${sc.id}: host filesystem collision writing ${f.path}" }
                target.parent.createDirectories()
                Files.write(target, f.content.toByteArray(Charsets.UTF_8))
            }
            val base = names(repo)
            check(base == prefixes(sc.files.map { it.path })) {
                "${sc.id}: host filesystem altered file names, found $base"
            }

            // Git decides whether a path is a directory by looking at the filesystem, and a trailing slash in the
            // argument is not enough for negated or directory-only rules; it can even make "*" match the empty
            // remainder. The slash is therefore removed from the argument. Each path is therefore materialized on its
            // own (directory when it ends in a slash, empty file otherwise), which also keeps names that differ only
            // by case or normalization from colliding on case-insensitive hosts.
            val resolved =
                sc.checks.map { c ->
                    val leaf = c.path.removeSuffix("/")
                    val target = repo.resolve(leaf)
                    if (c.path.endsWith("/")) {
                        check(
                            !target.exists() || Files.isDirectory(target),
                        ) { "${sc.id}: '${c.path}' is a file in the scenario" }
                        target.createDirectories()
                    } else {
                        check(!target.exists() || !Files.isDirectory(target)) {
                            "${sc.id}: '${c.path}' needs a trailing slash, it is a directory in the scenario"
                        }
                        target.parent.createDirectories()
                        if (!target.exists()) Files.write(target, ByteArray(0))
                    }
                    try {
                        val expected = prefixes(sc.files.map { it.path } + leaf)
                        val found = names(repo)
                        check(found == expected) {
                            "${sc.id}: host filesystem altered names for '${c.path}', expected $expected but found $found"
                        }
                        // Each record is source NUL line NUL pattern NUL path NUL, with empty fields for no match.
                        val output =
                            runGit(
                                listOf("git", "check-ignore", "--no-index", "-v", "-n", "-z", "--stdin"),
                                repo,
                                env,
                                leaf + "\u0000",
                                allowOne = true,
                            )
                        val fields = output.split("\u0000")
                        check(fields.size == 5) {
                            "${sc.id}: unexpected check-ignore output ${output.replace('\u0000', '|')}"
                        }
                        check(fields[3] == leaf) { "${sc.id}: Git answered for '${fields[3]}' instead of '$leaf'" }
                        if (fields[0].isEmpty()) {
                            CheckSpec(c.path, "NONE", null)
                        } else {
                            val result = if (fields[2].startsWith("!")) "INCLUDED" else "IGNORED"
                            CheckSpec(c.path, result, "${fields[0]}:${fields[1]}:${fields[2]}")
                        }
                    } finally {
                        removeNewEntries(repo, base)
                    }
                }
            return sc.copy(checks = resolved)
        } finally {
            deleteTree(tmp)
        }
    }
}

private fun names(repo: Path): Set<String> =
    Files.walk(repo).use { walk ->
        walk
            .map { entry -> repo.relativize(entry).joinToString("/") { it.toString() } }
            .filter { it.isNotEmpty() && it != ".git" && !it.startsWith(".git/") }
            .toList()
            .toSortedSet()
    }

private fun prefixes(paths: List<String>): Set<String> =
    paths
        .flatMap { path ->
            val parts = path.split("/")
            parts.indices.map { parts.take(it + 1).joinToString("/") }
        }.toSortedSet()

private fun removeNewEntries(
    repo: Path,
    keep: Set<String>,
) {
    val extra = names(repo) - keep
    for (name in extra.sortedDescending()) Files.deleteIfExists(repo.resolve(name))
}

private fun runGit(
    cmd: List<String>,
    dir: Path?,
    env: Map<String, String>,
    stdin: String?,
    allowOne: Boolean = false,
): String {
    val pb = ProcessBuilder(cmd)
    if (dir != null) pb.directory(dir.toFile())
    val pbEnv = pb.environment()
    val path = pbEnv["PATH"] ?: pbEnv["Path"] ?: ""
    val systemRoot = pbEnv["SystemRoot"]
    pbEnv.clear()
    pbEnv["PATH"] = path
    if (systemRoot != null) pbEnv["SystemRoot"] = systemRoot
    pbEnv["LC_ALL"] = "C"
    pbEnv.putAll(env)
    val err = Files.createTempFile("kignore-git-stderr", ".txt")
    try {
        pb.redirectError(err.toFile())
        val process = pb.start()
        process.outputStream.use { os -> if (stdin != null) os.write(stdin.toByteArray(Charsets.UTF_8)) }
        val out = String(process.inputStream.readAllBytes(), Charsets.UTF_8)
        val code = process.waitFor()
        // check-ignore exits 1 when nothing matched, which is a valid answer.
        check(code == 0 || (allowOne && code == 1)) {
            "${cmd.joinToString(" ")} failed with $code: ${err.readText()}"
        }
        return out
    } finally {
        Files.deleteIfExists(err)
    }
}

private fun deleteTree(root: Path) {
    Files.walk(root).use { walk ->
        for (p in walk.sorted(Comparator.reverseOrder()).toList()) {
            p.toFile().setWritable(true)
            Files.deleteIfExists(p)
        }
    }
}

// Output

private fun embedded(files: Map<String, String>): String {
    val b = StringBuilder()
    b.append("// Generated by GenerateFixtures. Do not edit.\n")
    b.append("package dev.cuervolu.kignore.conformance\n\n")
    b.append("internal object ConformanceData {\n")
    b.append("    val files: Map<String, String> by lazy {\n        mapOf(\n")
    for (name in files.keys) {
        b
            .append("            \"")
            .append(name)
            .append("\" to ")
            .append(identifier(name))
            .append("(),\n")
    }
    b.append("        )\n    }\n")
    for ((name, text) in files) {
        b.append("\n    private fun ").append(identifier(name)).append("(): String = lines(\n")
        for (line in text.split("\n")) b.append("        \"").append(kotlinLiteral(line)).append("\",\n")
        b.append("    )\n")
    }
    b.append("\n    private fun lines(vararg lines: String): String = lines.joinToString(\"\\n\")\n}\n")
    return b.toString()
}

private fun identifier(name: String): String =
    "file" +
        name.split(Regex("[^A-Za-z0-9]+")).filter { it.isNotEmpty() }.joinToString("") {
            it.replaceFirstChar(Char::uppercaseChar)
        }

private fun kotlinLiteral(s: String): String = s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

private fun checkAgainstDisk(generated: Map<String, String>) {
    val stale = ArrayList<String>()
    for ((name, text) in generated) {
        val file = FIXTURES.resolve("$name.txt")
        if (!file.exists() || withoutGitLine(file.readText()) != withoutGitLine(text)) {
            stale.add(file.toString())
        } else if (file.readText() != text) {
            System.err.println("Warning: $file was generated with a different Git version")
        }
    }
    val embedded = embedded(generated)
    if (!EMBEDDED.exists() || withoutGitLine(EMBEDDED.readText()) != withoutGitLine(embedded)) {
        stale.add(EMBEDDED.toString())
    }
    if (stale.isNotEmpty()) {
        System.err.println("Stale generated files:\n  " + stale.joinToString("\n  "))
        exitProcess(1)
    }
}

private fun withoutGitLine(s: String): String = s.replace(Regex("(?m)^(# git: |        \"# git: ).*$"), "")
